"use client";
import { useState } from "react";
import { useMutation } from "@tanstack/react-query";
import { getMatches } from "@/server/actions/ai";
import { Alert } from "@/components/arc/alert/alert";
import { Button } from "@/components/arc/button/button";
import { EmptyState } from "@/components/arc/empty-state/empty-state";
import { Input } from "@/components/arc/input/input";
import { Select } from "@/components/arc/select/select";
import { Skeleton } from "@/components/arc/skeleton/skeleton";
import { ProjectCard } from "@/components/ProjectCard";
import { SampleChip } from "@/components/SampleChip";

type Meta = { full_name: string; is_seed: number; contributing_url: string | null; html_url: string | null };

// Values are part of the ai_briefs cache key: keep them stable.
const HOURS = ["About 1 hour", "About 3 hours", "6+ hours"];

export function DiscoverClient({ projects }: { projects: Meta[] }) {
  const [skills, setSkills] = useState("TypeScript, React, writing docs");
  const [hours, setHours] = useState(HOURS[1]);
  const meta = new Map(projects.map((p) => [p.full_name, p]));
  const run = useMutation({ mutationFn: (force: boolean) => getMatches(skills, hours, force) });
  const res = run.data;
  const anySeed = res?.ok && res.data.some((m) => meta.get(m.project)?.is_seed === 1);

  return (
    <>
      <form
        className="card discover-form"
        onSubmit={(e) => {
          e.preventDefault();
          run.mutate(false);
        }}
      >
        <h1>Find a project that fits you</h1>
        <div className="discover-row">
          <div className="discover-skills">
            <Input id="skills" label="Tell us what you know" value={skills} onChange={(e) => setSkills(e.target.value)} required />
          </div>
          <div className="discover-time">
            <Select label="Time per week" value={hours} onValueChange={setHours} options={HOURS.map((h) => ({ value: h, label: h }))} />
          </div>
          <div className="discover-actions">
            <Button type="submit" loading={run.isPending}>
              Match me
            </Button>
            {res?.ok && (
              <Button variant="ghost" disabled={run.isPending} onClick={() => run.mutate(true)}>
                Regenerate
              </Button>
            )}
          </div>
        </div>
      </form>

      {(run.isPending || res) && (
        <div className="discover-results-head">
          <h2>Projects using Vouch that match</h2>
          {anySeed && <SampleChip show />}
        </div>
      )}

      {run.isPending && (
        <div className="discover-grid" aria-busy="true" aria-label="AI is ranking projects">
          {[0, 1, 2].map((i) => (
            <div key={i} className="card discover-card">
              <Skeleton label="AI is ranking projects" lines={4} />
            </div>
          ))}
        </div>
      )}
      {run.error && (
        <Alert tone="danger" title="Something went wrong" role="alert">
          {String(run.error)}
        </Alert>
      )}
      {!run.isPending && res && !res.ok && (
        <Alert tone="warning" role="alert" title={res.error.code === "model_unavailable" ? "Model unavailable" : "Invalid model output"}>
          {res.error.message}
        </Alert>
      )}
      {!run.isPending && res?.ok && (
        <>
          {res.data.length === 0 && (
            <div className="card">
              <EmptyState title="No matches" description="No indexed project fits these skills yet. Try broader words." />
            </div>
          )}
          <div className="discover-grid">
            {res.data.map((m) => {
              const p = meta.get(m.project);
              return (
                <ProjectCard
                  key={m.project}
                  {...m}
                  is_seed={p?.is_seed === 1}
                  contributing_url={p?.contributing_url ?? null}
                  html_url={p?.html_url ?? null}
                />
              );
            })}
          </div>
          <p className="muted small">
            <span className="mono">{res.model}</span> · {res.cached ? "cached" : "generated"}{" "}
            {new Date(res.created_at).toLocaleString()}
          </p>
        </>
      )}
      <p className="discover-footer">
        Match reasons are generated by AI from your input and public project data. Your query is cached locally
        only.
      </p>
    </>
  );
}
